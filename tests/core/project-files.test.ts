function project(root: string, modules: string[] = []): ProjectInfo {
  return {
    root,
    framework: modules.length ? "nuxt" : "vue",
    ssr: false,
    vueVersion: "3.5.0",
    isMonorepo: false,
    nuxt: modules.length
      ? ({ modules: modules.map((name) => ({ name })) } as ProjectInfo["nuxt"])
      : undefined,
  };
}

async function globFiles(root: string, include: string[], exclude: string[]) {
  const files = new Set<string>();
  for (const pattern of include) {
    for await (const entry of glob(pattern, { cwd: root, exclude })) {
      const absolute = resolve(root, entry);
      if (statSync(absolute, { throwIfNoEntry: false })?.isFile()) files.add(absolute);
    }
  }
  return [...files].sort();
}

async function withFixture(files: Record<string, string>, run: (root: string) => Promise<void>) {
  const root = await mkdtemp(join(tmpdir(), "vite-doctor-project-files-"));
  try {
    for (const [file, source] of Object.entries(files)) write(root, file, source);
    await run(root);
  } finally {
    rmSync(root, { recursive: true, force: true });
  }
}

function write(root: string, file: string, source: string) {
  const absolute = join(root, file);
  mkdirSync(dirname(absolute), { recursive: true });
  writeFileSync(absolute, source);
}
