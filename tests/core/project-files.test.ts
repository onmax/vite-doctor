test("a later Doctor Run sees files added after the previous run", async () => {
  await withFixture({ "package.json": "{}", "src/a.ts": "export const a = 1\n" }, async (root) => {
    const first = await createScanSession({ root, framework: "vue", cache: false });
    write(root, "src/b.js", "export const b = 1\n");
    const second = await createScanSession({ root, framework: "vue", cache: false });
    expect(first.files.map((file) => file.displayPath)).toEqual(["src/a.ts"]);
    expect(first.project.languages).toEqual(["typescript"]);
    expect(second.files.map((file) => file.displayPath)).toEqual(["src/a.ts", "src/b.js"]);
    expect(second.project.languages).toEqual(["typescript", "javascript"]);

    write(root, "src/c.ts", "export const c = 1\n");
    const again = await selectScanFiles(root, second.config, {}, second.project);
    expect(again.map((file) => file.displayPath)).toEqual(["src/a.ts", "src/b.js", "src/c.ts"]);
  });
});

test("Nuxt manifest freshness is shared within a run and recomputed by the next run", async () => {
  await withFixture(
    {
      "package.json": JSON.stringify({ dependencies: { nuxt: "4.4.6" } }),
      "nuxt.config.ts": "export default defineNuxtConfig({ future: { compatibilityVersion: 4 } })",
      "server/api/hello.ts": "export default defineEventHandler(() => 'hi')\n",
    },
    async (root) => {
      write(
        root,
        ".nuxt/doctor.manifest.json",
        JSON.stringify({
          generatedAt: new Date(Date.now() + 1000).toISOString(),
          compatibilityVersion: 5,
          autoImportEnabled: true,
          nuxtConfigMtimeMs: statSync(join(root, "nuxt.config.ts")).mtimeMs,
          serverInventory: { "server/api": ["hello.ts"] },
          layers: [],
        }),
      );
      const fresh = await detectProject(root);
      expect(fresh.nuxt?.manifest?.isCurrent).toBe(true);
      expect(fresh.nuxt?.autoImportsAuthoritative).toBe(true);
      expect(fresh.nuxtCompatibility).toMatchObject({ version: 5, provenance: "manifest" });

      write(root, "server/api/new.ts", "export default defineEventHandler(() => 'new')\n");
      const stale = await detectProject(root);
      expect(stale.nuxt?.manifest?.isCurrent).toBe(false);
      expect(stale.nuxt?.autoImportsAuthoritative).toBe(false);
      expect(stale.nuxtCompatibility).toMatchObject({ version: 4, provenance: "config" });
      expect(stale.nuxt?.serverDirs.api).toEqual([
        join(root, "server/api/hello.ts"),
        join(root, "server/api/new.ts"),
      ]);
    },
  );
});

