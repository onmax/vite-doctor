import { selectScanFiles } from "../../../../core/internal/source-inventory.js";
import { walkScriptLocal, type AnyNode } from "../../../../core/rule-authoring.js";
import { dirname, join, relative, resolve } from "pathe";
import type { RuleContext } from "../../../../core/index.js";
import { projectWorkspacePackages } from "../../../../core/internal/applicability.js";
import { owningWorkspacePackage } from "../../../../core/internal/workspace-packages.js";

export const NUXT_APP_DIRS = new Set([
  "assets",
  "components",
  "composables",
  "layouts",
  "middleware",
  "pages",
  "plugins",
  "utils",
]);

export type NuxtFileClass =
  | "runtime-app"
  | "server-runtime"
  | "config-build"
  | "content-docs"
  | "generated"
  | "external-package"
  | "unknown";

export interface NuxtAppSource {
  root: string;
  srcDir: string;
  serverDir: string;
}

export function classifyNuxtFile(ctx: RuleContext): NuxtFileClass {
  const relativePath = toPosixPath(ctx.file.relativePath);
  if (isGeneratedFile(ctx)) return "generated";
  if (isContentDocsPath(relativePath, ctx.file.sourceKind)) return "content-docs";
  const file = toPosixPath(resolve(ctx.project.root, ctx.file.path));
  const source = owningNuxtAppSource(ctx, file);
  const appPath = source ? relative(source.root, file) : relativePath;
  if (isConfigBuildPath(relativePath) || isConfigBuildPath(appPath)) return "config-build";
  if (
    ctx.helpers.isNuxtServerFile(relativePath) ||
    (source && isNuxtServerPath(ctx, source, file, appPath))
  )
    return "server-runtime";
  if (source && ctx.file.sourceKind !== "module" && isRuntimeAppPath(source, file, appPath))
    return "runtime-app";
  if (isExternalPackagePath(relativePath)) return "external-package";
  return "unknown";
}

export function isGeneratedFile(ctx: RuleContext) {
  const relativePath = toPosixPath(ctx.file.relativePath);
  if (
    relativePath.startsWith("shared/types/lexicons/") ||
    relativePath.startsWith("app/generated/") ||
    relativePath.startsWith("generated/")
  )
    return true;
  return /@generated|generated by|do not edit|auto-generated/i.test(ctx.file.text.slice(0, 800));
}

export function isRuntimeAppFile(ctx: RuleContext) {
  return classifyNuxtFile(ctx) === "runtime-app";
}

/**
 * App code whose routes Nuxt owns: a Nuxt app file, or a file in a Nuxt module's `runtime/` app
 * code, in a workspace package that does not create its own vue-router instance, as a Vue SPA
 * shipped next to a Nuxt module does.
 */
export async function isNuxtRoutedAppFile(ctx: RuleContext) {
  const file = toPosixPath(resolve(ctx.project.root, ctx.file.path));
  const appFile =
    isRuntimeAppFile(ctx) ||
    (ctx.file.sourceKind !== "module" && isModuleRuntimeAppFile(ctx, file));
  return appFile && !(await createsVueRouter(ctx));
}

export function isServerRuntimeFile(ctx: RuleContext) {
  return classifyNuxtFile(ctx) === "server-runtime";
}

export function isContentDocsFile(ctx: RuleContext) {
  return classifyNuxtFile(ctx) === "content-docs";
}

export function isConfigBuildFile(ctx: RuleContext) {
  return classifyNuxtFile(ctx) === "config-build";
}

export function isNuxtRuntimeFile(ctx: RuleContext) {
  return isRuntimeAppFile(ctx);
}

export function isExplicitlyScannedByNuxt(ctx: RuleContext, kind: "imports" | "shared") {
  if (isGeneratedFile(ctx)) return true;
  const manifest = ctx.project.nuxt?.manifest;
  if (!manifest) return false;
  // A shared folder can also be scanned through imports.dirs.
  const roots =
    kind === "imports"
      ? manifest.importsDirs
      : [...manifest.sharedScanRoots, ...manifest.importsDirs];
  if (!roots.length) return false;
  const relativePath = toPosixPath(relative(ctx.project.root, ctx.file.path));
  return roots
    .map((root) => normalizeScanRoot(ctx, root))
    .filter(Boolean)
    .filter((root) =>
      kind === "imports" && !root.includes("*")
        ? root !== "app/composables" && root !== "composables"
        : root !== "shared/utils" && root !== "shared/types",
    )
    .some((root) => matchesScanRoot(relativePath, root));
}

export function isExplicitPlugin(ctx: RuleContext) {
  const manifest = ctx.project.nuxt?.manifest;
  if (!manifest?.hasManifest) return false;
  return manifest.pluginFiles.some((file) => resolveSameFile(file, ctx.file.path));
}

/** The file's path inside its Nuxt app's `pages/` directory, or null outside one. */
export function nuxtPagePath(ctx: RuleContext): string | null {
  const file = toPosixPath(resolve(ctx.project.root, ctx.file.path));
  const source = owningNuxtAppSource(ctx, file);
  if (!source) return null;
  const pagesDir = `${source.srcDir}/pages`;
  return isInside(file, pagesDir) && file !== pagesDir ? relative(pagesDir, file) : null;
}

export function resolveSameFile(a: string, b: string) {
  return toPosixPath(a) === toPosixPath(b);
}

export function toPosixPath(path: string) {
  return path.replace(/\\/g, "/");
}

// Nuxt loads a module's runtime directory into the apps that install it; `runtime/server` is Nitro.
function isModuleRuntimeAppFile(ctx: RuleContext, file: string): boolean {
  return (ctx.project.nuxtModuleDefinitions ?? []).some((definition) => {
    if (!definition.runtimeDir) return false;
    const dir = toPosixPath(definition.runtimeDir);
    return isInside(file, dir) && !isInside(file, `${dir}/server`);
  });
}

async function createsVueRouter(ctx: RuleContext): Promise<boolean> {
  const packages = projectWorkspacePackages(ctx.project);
  const owner = owningWorkspacePackage(packages, toPosixPath(ctx.file.relativePath));
  const key = `nuxt:creates-vue-router:${owner}`;
  const cached = ctx.cache.get<boolean>(key);
  if (cached !== undefined) return cached;
  const entries = await selectScanFiles(ctx.project.root, {}, {}, ctx.project);
  for (const entry of entries) {
    if (
      entry.sourceKind === "module" ||
      owningWorkspacePackage(packages, toPosixPath(relative(ctx.project.root, entry.path))) !==
        owner
    )
      continue;
    const text = ctx.fs.readText(entry.path);
    if (!text || !text.includes("vue-router")) continue;
    const ast = entry.path.endsWith(".vue")
      ? (await parseSfcFile(entry.path, text)).getScriptAst()
      : parseScript(entry.path, text);
    if (!ast) continue;
    const bindings = new Set<string>();
    for (const node of (ast.body ?? []) as AnyNode[]) {
      if (
        node.type !== "ImportDeclaration" ||
        node.source?.value !== "vue-router" ||
        node.importKind === "type"
      )
        continue;
      for (const specifier of node.specifiers ?? []) {
        if (specifier.importKind !== "type" && specifier.imported?.name === "createRouter")
          bindings.add(specifier.local.name);
      }
    }
    let found = false;
    walkScriptLocal(ast, (node) => {
      if (
        node.type === "CallExpression" &&
        node.callee?.type === "Identifier" &&
        bindings.has(node.callee.name)
      )
        found = true;
    });
    if (found) {
      ctx.cache.set(key, true);
      return true;
    }
  }
  ctx.cache.set(key, false);
  return false;
}

function owningNuxtAppSource(ctx: RuleContext, file: string) {
  let owner: NuxtAppSource | undefined;
  for (const source of nuxtAppSources(ctx)) {
    if (isInside(file, source.root) && (!owner || source.root.length > owner.root.length))
      owner = source;
  }
  return owner;
}

// Nuxt roots come from manifest layers or every detected nuxt.config, so nested apps such as
// docs/ each get their own srcDir instead of treating the whole app root as app code.
export function nuxtAppSources(ctx: RuleContext): NuxtAppSource[] {
  const key = "nuxt:app-sources";
  const cached = ctx.cache.get<NuxtAppSource[]>(key);
  if (cached) return cached;
  const nuxt = ctx.project.nuxt;
  const layers = (nuxt?.layers ?? []).map((layer) => ({
    ...layer,
    root: toPosixPath(resolve(ctx.project.root, layer.root)),
  }));
  const primaryRoot =
    layers.find((layer) => layer.priority === 0)?.root ?? toPosixPath(ctx.project.root);
  const roots = new Set([
    ...(nuxt?.appRoots ?? []).map((root) => toPosixPath(resolve(ctx.project.root, root))),
    ...layers.map((layer) => layer.root),
    primaryRoot,
  ]);
  const sources = [...roots].map((root): NuxtAppSource => {
    const layer = layers.find((candidate) => candidate.root === root);
    const srcDir = layer?.srcDir
      ? resolve(root, layer.srcDir)
      : root === primaryRoot && nuxt?.appDir
        ? resolve(ctx.project.root, nuxt.appDir)
        : ctx.fs.exists(join(root, "app"))
          ? join(root, "app")
          : root;
    return {
      root,
      srcDir: toPosixPath(srcDir),
      serverDir: toPosixPath(
        layer?.serverDir ? resolve(root, layer.serverDir) : join(root, "server"),
      ),
    };
  });
  ctx.cache.set(key, sources);
  return sources;
}

function isNuxtServerPath(ctx: RuleContext, source: NuxtAppSource, file: string, appPath: string) {
  return (
    ctx.helpers.isNuxtServerFile(appPath) ||
    isInside(file, source.serverDir) ||
    isInside(file, `${source.srcDir}/server`)
  );
}

function isRuntimeAppPath(source: NuxtAppSource, file: string, appPath: string) {
  if (source.srcDir !== source.root) return isInside(file, source.srcDir);
  if (appPath.startsWith("app/") || /^(app|error)\.vue$/.test(appPath)) return true;
  const [first] = appPath.split("/");
  return !!first && NUXT_APP_DIRS.has(first);
}

function isInside(file: string, dir: string) {
  return file === dir || file.startsWith(`${dir}/`);
}

function isContentDocsPath(relativePath: string, sourceKind: string | undefined) {
  return (
    sourceKind === "content" ||
    /\.(md|mdc|markdown)$/.test(relativePath) ||
    relativePath.startsWith("content/")
  );
}

function isConfigBuildPath(relativePath: string) {
  return (
    /(^|\/)(nuxt|content|vite|vitest|eslint|tailwind|uno|app)\.config\.[cm]?[jt]s$/.test(
      relativePath,
    ) ||
    /(^|\/)package\.json$/.test(relativePath) ||
    /^(config|scripts|tools|test|tests|\.github)\//.test(relativePath)
  );
}

function isExternalPackagePath(relativePath: string) {
  return /^(cli|packages|connector|docs)\//.test(relativePath);
}

function normalizeScanRoot(ctx: RuleContext, root: string) {
  let normalized = toPosixPath(root);
  const projectRoot = `${toPosixPath(ctx.project.root)}/`;
  if (normalized.startsWith(projectRoot)) normalized = normalized.slice(projectRoot.length);
  else normalized = toPosixPath(relative(ctx.project.root, normalized));
  normalized = normalized.replace(/^~\//, "app/").replace(/^@\//, "app/");
  normalized = normalized.replace(/^\.\//, "");
  if (normalized.startsWith("composables/") && ctx.file.relativePath.startsWith("app/composables/"))
    return `app/${normalized}`;
  return normalized;
}

function matchesScanRoot(relativePath: string, root: string) {
  if (root.includes("*")) return globToRegExp(root).test(relativePath);
  // Nuxt/Unimport scans only immediate files of a configured directory.
  return relativePath === root || dirname(relativePath) === root;
}

function globToRegExp(glob: string) {
  const pattern = glob
    .split("/")
    .map((part) =>
      part === "**" ? ".*" : part.replace(/[.+?^${}()|[\]\\]/g, "\\$&").replaceAll("*", "[^/]*"),
    )
    .join("/");
  return new RegExp(`^${pattern}$`);
}
